export function normalizeWijkSlug(slug?: string): string {
  if (!slug) return "";
  const cleaned = slug.toLowerCase().trim();
  return SLUG_ALIASES[cleaned] || cleaned;
}

export function getWijkOrKernBySlug(slug?: string): WijkOfKern | undefined {
  if (!slug) return undefined;
  const target = normalizeWijkSlug(slug);
  return WIJKEN_EN_KERNEN.find((w) => w.slug.toLowerCase() === target);
}
